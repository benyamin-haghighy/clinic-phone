function isFiniteVerb(token) {
    if (!token) return false
    if (FINITE_VERBS.has(token)) return true
    if (PRESENT_PREFIX_RE.test(token) && !PRESENT_PREFIX_NOT.has(token)) return true
    if (PERFECT_RE.test(token)) return true
    return false
}

