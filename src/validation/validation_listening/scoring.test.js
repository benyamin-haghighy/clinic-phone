const origLog = console.log
let pass = 0
const fails = []

for (const [text, expected] of CASES) {
    const r = evaluate(text)
    if (r.complete === expected) pass++
    else fails.push({ text, expected, score: r.score, reasons: r.reasons })
}

origLog(`\n${pass}/${CASES.length} passed`)
if (fails.length) {
    origLog('\nFAILED:')
    for (const f of fails) {
        origLog(`  [${f.score}] expected ${f.expected ? 'COMPLETE' : 'INCOMPLETE'} | «${f.text}» | ${f.reasons.join(' ; ')}`)
    }
    process.exitCode = 1
}
